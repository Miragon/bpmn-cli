#!/usr/bin/env node
/**
 * Writes the vendor descriptors the core reads as data, as TypeScript
 * constants (the installed versions of the development dependencies):
 *
 *   src/platform/camunda-descriptor.ts  Camunda 7: camunda-bpmn-moddle's resources/camunda.json
 *   src/platform/zeebe-descriptor.ts    Camunda 8: zeebe-bpmn-moddle's resources/zeebe.json
 *
 *   node tools/gen-camunda-descriptor.mjs          # after updating camunda-bpmn-moddle or zeebe-bpmn-moddle
 *   node tools/gen-camunda-descriptor.mjs --check  # exit 1 when a file is stale
 *
 * Why a copy: src/platform/descriptor.ts used to read the JSON with
 * createRequire (node:module), which a browser bundle cannot resolve; a JSON
 * import attribute warns on Node 20 / 22. The constant needs neither. The
 * data stays exactly the package's (test/isomorphic.test.ts compares it with
 * the installed JSON), including the package's licence notice.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(ROOT, 'package.json'));

const TARGETS = [
  { pkg: 'camunda-bpmn-moddle', json: 'camunda.json', file: 'camunda-descriptor.ts', constant: 'CAMUNDA_DESCRIPTOR', what: 'Camunda 7', reader: 'src/platform/descriptor.ts' },
  { pkg: 'zeebe-bpmn-moddle', json: 'zeebe.json', file: 'zeebe-descriptor.ts', constant: 'ZEEBE_DESCRIPTOR', what: 'Camunda 8 (Zeebe)', reader: 'src/platform/zeebe.ts' },
];

/** One line per type (and per association / enumeration), the rest as JSON. */
function render(value) {
  const lines = ['{'];
  const keys = Object.keys(value);
  keys.forEach((key, i) => {
    const comma = i < keys.length - 1 ? ',' : '';
    const v = value[key];
    if (Array.isArray(v) && v.length) {
      lines.push(`  ${JSON.stringify(key)}: [`);
      v.forEach((item, j) => lines.push(`    ${JSON.stringify(item)}${j < v.length - 1 ? ',' : ''}`));
      lines.push(`  ]${comma}`);
    } else {
      lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(v)}${comma}`);
    }
  });
  lines.push('}');
  return lines.join('\n');
}

function generate(t) {
  const pkgDir = dirname(require.resolve(`${t.pkg}/package.json`));
  const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
  const json = JSON.parse(readFileSync(join(pkgDir, 'resources', t.json), 'utf8'));
  const licence = readFileSync(join(pkgDir, 'LICENSE'), 'utf8').trim();
  const text = `/**
 * GENERATED by tools/gen-camunda-descriptor.mjs from ${t.pkg}@${version}
 * (resources/${t.json}). Do not edit: run \`node tools/gen-camunda-descriptor.mjs\`
 * after updating that dependency (test/isomorphic.test.ts fails while it is stale).
 *
 * The descriptor as a constant, so that the core reads it without file access
 * or a JSON import (see ${t.reader}). Licence of the data:
 *
${licence.split('\n').map((l) => (l ? ` * ${l}` : ' *')).join('\n')}
 */

/** ${t.pkg}'s descriptor, verbatim. */
export const ${t.constant}_VERSION = ${JSON.stringify(version)};

export const ${t.constant}: { types: unknown[]; [key: string]: unknown } = ${render(json)};
`;
  return { text, version, types: json.types.length, out: join(ROOT, 'src', 'platform', t.file) };
}

const check = process.argv.includes('--check');
let stale = false;
for (const t of TARGETS) {
  const { text, version, types, out } = generate(t);
  if (check) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      /* missing: stale */
    }
    if (current !== text) {
      console.error(`src/platform/${t.file} is stale (${t.pkg}@${version}): run node tools/gen-camunda-descriptor.mjs`);
      stale = true;
    } else {
      console.log(`src/platform/${t.file} is up to date (${t.pkg}@${version})`);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote src/platform/${t.file} (${t.pkg}@${version}, ${types} types)`);
  }
}
if (stale) process.exit(1);
