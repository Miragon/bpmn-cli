#!/usr/bin/env node
/**
 * Writes src/platform/camunda-descriptor.ts: the Camunda 7 descriptor
 * (`camunda-bpmn-moddle`'s resources/camunda.json, the installed version) as
 * a TypeScript constant.
 *
 *   node tools/gen-camunda-descriptor.mjs          # after updating camunda-bpmn-moddle
 *   node tools/gen-camunda-descriptor.mjs --check  # exit 1 when the file is stale
 *
 * Why a copy: src/platform/descriptor.ts used to read the JSON with
 * createRequire (node:module), which a browser bundle cannot resolve; a JSON
 * import attribute warns on Node 20 / 22. The constant needs neither. The
 * data stays exactly the package's (test/isomorphic.test.ts compares it with
 * the installed JSON), including the package's licence notice.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'platform', 'camunda-descriptor.ts');

const require = createRequire(join(ROOT, 'package.json'));
const pkgDir = dirname(require.resolve('camunda-bpmn-moddle/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const json = JSON.parse(readFileSync(join(pkgDir, 'resources', 'camunda.json'), 'utf8'));
const licence = readFileSync(join(pkgDir, 'LICENSE'), 'utf8').trim();

/** One line per type (and per association / enumeration), the rest as JSON. */
function render(value) {
  const lines = ['{'];
  const keys = Object.keys(value);
  keys.forEach((key, i) => {
    const comma = i < keys.length - 1 ? ',' : '';
    const v = value[key];
    if (Array.isArray(v) && v.length) {
      lines.push(`  ${JSON.stringify(key)}: [`);
      v.forEach((item, j) => lines.push(`    ${JSON.stringify(item)}${j < v.length - 1 ? ',' : ''}`));
      lines.push(`  ]${comma}`);
    } else {
      lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(v)}${comma}`);
    }
  });
  lines.push('}');
  return lines.join('\n');
}

const text = `/**
 * GENERATED by tools/gen-camunda-descriptor.mjs from camunda-bpmn-moddle@${version}
 * (resources/camunda.json). Do not edit: run \`node tools/gen-camunda-descriptor.mjs\`
 * after updating that dependency (test/isomorphic.test.ts fails while it is stale).
 *
 * The descriptor as a constant, so that the core reads it without file access
 * or a JSON import (see src/platform/descriptor.ts). Licence of the data:
 *
${licence.split('\n').map((l) => (l ? ` * ${l}` : ' *')).join('\n')}
 */

/** camunda-bpmn-moddle's descriptor, verbatim. */
export const CAMUNDA_DESCRIPTOR_VERSION = ${JSON.stringify(version)};

export const CAMUNDA_DESCRIPTOR: { types: unknown[]; [key: string]: unknown } = ${render(json)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing: stale */
  }
  if (current !== text) {
    console.error(`src/platform/camunda-descriptor.ts is stale (camunda-bpmn-moddle@${version}): run node tools/gen-camunda-descriptor.mjs`);
    process.exit(1);
  }
  console.log(`src/platform/camunda-descriptor.ts is up to date (camunda-bpmn-moddle@${version})`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/platform/camunda-descriptor.ts (camunda-bpmn-moddle@${version}, ${json.types.length} types)`);
}
